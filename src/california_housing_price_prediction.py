import numpy as np
import pandas as pd
import joblib

from scipy import stats

from sklearn.model_selection import train_test_split,cross_val_score,GridSearchCV

from sklearn.impute import SimpleImputer

from sklearn.preprocessing import OneHotEncoder,StandardScaler,FunctionTransformer

from sklearn.pipeline import Pipeline, make_pipeline

from sklearn.compose import ColumnTransformer

from sklearn.metrics.pairwise import rbf_kernel

from sklearn.tree import DecisionTreeRegressor

from sklearn.linear_model import LinearRegression

from sklearn.metrics import mean_absolute_error,mean_squared_error,r2_score,root_mean_squared_error

"""# Load Database"""

housing = pd.read_csv(
    "california_housing_prices.csv"
)

"""# Stratified Train / Test Split"""

housing["income_category"] = pd.cut(
    housing["median_income"],
    bins=[0., 1.5, 3., 4.5, 6., np.inf],
    labels=[1, 2, 3, 4, 5]
)

train_set, test_set = train_test_split(
    housing,
    test_size=0.2,
    random_state=40,
    stratify=housing["income_category"]
)

train_set = train_set.drop(columns="income_category")
test_set = test_set.drop(columns="income_category")

"""# Separate Features & Target

"""

train_features = train_set.drop(
    columns="median_house_value"
)

train_target = train_set["median_house_value"]

test_features = test_set.drop(
    columns="median_house_value"
)

test_target = test_set["median_house_value"]

"""# Feature Engineering Functions"""

def ratio_of_columns(X):
    return X[:, [0]] / X[:, [1]]


def ratio_feature_name(transformer, feature_names_in):
    return ["ratio"]

"""# Feature Engineering Pipelines"""

def ratio_pipeline():

    return make_pipeline(

        SimpleImputer(strategy="median"),

        FunctionTransformer(
            ratio_of_columns,
            feature_names_out=ratio_feature_name
        ),

        StandardScaler()

    )


heavy_tail_pipeline = make_pipeline(

    SimpleImputer(strategy="median"),

    FunctionTransformer(
        np.log,
        feature_names_out="one-to-one"
    ),

    StandardScaler()

)

housing_age_pipeline = FunctionTransformer(

    rbf_kernel,

    feature_names_out="one-to-one",

    kw_args={
        "Y": [[35]],
        "gamma": 0.1
    }

)

default_numeric_pipeline = make_pipeline(

    SimpleImputer(strategy="median"),

    StandardScaler()

)

categorical_pipeline = Pipeline([

    (
        "imputer",
        SimpleImputer(strategy="most_frequent")
    ),

    (
        "encoder",
        OneHotEncoder()
    )

])

all_transformations = ColumnTransformer(

    [

        (
            "bedrooms_per_room",
            ratio_pipeline(),
            ["total_bedrooms", "total_rooms"]
        ),

        (
            "rooms_per_house",
            ratio_pipeline(),
            ["total_rooms", "households"]
        ),

        (
            "people_per_house",
            ratio_pipeline(),
            ["population", "households"]
        ),

        (
            "log_features",
            heavy_tail_pipeline,
            [
                "total_bedrooms",
                "total_rooms",
                "population",
                "households",
                "median_income"
            ]
        ),

        (
            "housing_age_rbf",
            housing_age_pipeline,
            ["housing_median_age"]
        ),

        (
            "categorical",
            categorical_pipeline,
            ["ocean_proximity"]
        )

    ],

    remainder=default_numeric_pipeline

)

"""# Transform Training Data"""

train_features_transformed = all_transformations.fit_transform(
    train_features
)

"""# Feature Names"""

feature_names = all_transformations.get_feature_names_out()

"""# Linear Regression Pipeline"""

linear_regression_pipeline = Pipeline(

    [

        (
            "preprocessing",
            all_transformations
        ),

        (
            "model",
            LinearRegression()
        )

    ]

)

"""# Decision Tree Pipeline"""

decision_tree_pipeline = Pipeline(

    [

        (
            "preprocessing",
            all_transformations
        ),

        (
            "model",
            DecisionTreeRegressor(
                random_state=40
            )
        )

    ]

)

"""# Train Linear Regression"""

linear_regression_pipeline.fit(

    train_features,
    train_target

)

linear_predictions = linear_regression_pipeline.predict(
    train_features
)

"""# Linear Regression Metrics"""

linear_mae = mean_absolute_error(
    train_target,
    linear_predictions
)

linear_rmse = mean_squared_error(
    train_target,
    linear_predictions,
   )

linear_root = root_mean_squared_error(
    train_target,
    linear_predictions,
   )

linear_r2 = r2_score(
    train_target,
    linear_predictions
)

print("=" * 60)
print("Linear Regression")
print("=" * 60)

print(f"MAE  : {linear_mae:.2f}")
print(f"RMSE : {linear_rmse:.2f}")
print(f"root : {linear_root:.2f}")
print(f"R²   : {linear_r2:.4f}")

"""# Cross Validation"""

linear_cv = -cross_val_score(

    linear_regression_pipeline,

    train_features,

    train_target,

    scoring="neg_mean_absolute_error",

    cv=5

)

print("\nCross Validation (Linear Regression)")
print(pd.Series(linear_cv).describe())

"""# Train Decision Tree"""

decision_tree_pipeline.fit(

    train_features,
    train_target

)

decision_tree_predictions = decision_tree_pipeline.predict(
    train_features
)

"""# Decision Tree Metrics

"""

decision_tree_mae = mean_absolute_error(
    train_target,
    decision_tree_predictions
)

decision_tree_rmse = mean_squared_error(
    train_target,
    decision_tree_predictions
)

decision_tree_root = root_mean_squared_error(
    train_target,
    decision_tree_predictions
)

decision_tree_r2 = r2_score(
    train_target,
    decision_tree_predictions
)

print("\n" + "=" * 60)
print("Decision Tree")
print("=" * 60)

print(f"MAE  : {decision_tree_mae:.2f}")
print(f"RMSE : {decision_tree_rmse:.2f}")
print(f"root : {decision_tree_root:.2f}")
print(f"R²   : {decision_tree_r2:.4f}")

"""# Cross Validation (Decision Tree)"""

decision_tree_cv = -cross_val_score(

    decision_tree_pipeline,

    train_features,

    train_target,

    scoring="neg_mean_absolute_error",

    cv=5

)

print("\nCross Validation (Decision Tree)")
print(pd.Series(decision_tree_cv).describe())

"""# Compare Models"""

comparison = pd.DataFrame({

    "Model": [

        "Linear Regression",
        "Decision Tree"

    ],

    "MAE": [

        linear_mae,
        decision_tree_mae

    ],

    "RMSE": [

        linear_rmse,
        decision_tree_rmse

    ],

    "ROOT": [

        linear_root,
        decision_tree_root

    ],


    "R2": [

        linear_r2,
        decision_tree_r2

    ],

    "Cross Validation MAE": [

        linear_cv.mean(),
        decision_tree_cv.mean()

    ]

})

print("\n")
print("=" * 60)
print("Model Comparison")
print("=" * 60)
print(comparison)

"""# Hyperparameter Tuning"""

grid_parameters = {

    "preprocessing__housing_age_rbf__kw_args": [

        {

            "Y": [[35.0]],
            "gamma": 0.1

        },

        {

            "Y": [[35.0]],
            "gamma": 0.2

        }

    ],

    "model__max_depth": [

        5,
        10,
        15

    ]

}

grid_search = GridSearchCV(

    estimator=decision_tree_pipeline,

    param_grid=grid_parameters,

    scoring="neg_mean_absolute_error",

    cv=5,

    n_jobs=1

)

grid_search.fit(

    train_features,
    train_target

)

"""# Best Model"""

best_model = grid_search.best_estimator_

print("\n")
print("=" * 60)
print("Best Parameters")
print("=" * 60)

print(grid_search.best_params_)

"""# Cross Validation Results"""

cv_results = pd.DataFrame(

    grid_search.cv_results_

)

cv_results = cv_results.sort_values(

    by="mean_test_score",

    ascending=False

)

print("\nTop GridSearch Results")

print(

    cv_results[

        [

            "params",
            "mean_test_score",
            "std_test_score"

        ]

    ].head(10)

)

"""# Evaluate Best Model on Test Set"""

test_predictions = best_model.predict(test_features)

test_mae = mean_absolute_error(
    test_target,
    test_predictions
)

test_rmse = mean_squared_error(
    test_target,
    test_predictions
)

test_root = root_mean_squared_error(
    test_target,
    test_predictions
)

test_r2 = r2_score(
    test_target,
    test_predictions
)

print("\n")
print("=" * 60)
print("Final Test Performance")
print("=" * 60)

print(f"MAE  : {test_mae:.2f}")
print(f"RMSE : {test_rmse:.2f}")
print(f"ROOT : {test_root:.2f}")
print(f"R²   : {test_r2:.4f}")

"""# Feature Importance"""

feature_importance = pd.DataFrame({

    "Feature": feature_names,

    "Importance": best_model.named_steps[
        "model"
    ].feature_importances_

})

feature_importance = feature_importance.sort_values(

    by="Importance",

    ascending=False

)

print("\n")
print("=" * 60)
print("Top 20 Most Important Features")
print("=" * 60)

print(feature_importance.head(20))

"""# Confidence Interval of RMSE"""

squared_errors = (

    test_predictions -
    test_target

) ** 2

confidence = 0.95

rmse_interval = np.sqrt(

    stats.t.interval(

        confidence,

        len(squared_errors) - 1,

        loc=squared_errors.mean(),

        scale=stats.sem(squared_errors)

    )

)

print("\n")
print("=" * 60)
print("95% Confidence Interval (RMSE)")
print("=" * 60)

print(rmse_interval)

"""# Save Best Model"""

joblib.dump(

    best_model,

    "housing_model.pkl"

)

"""# Load Model"""

loaded_model = joblib.load(
    "housing_model.pkl"
)

"""# Predict First Five Houses"""

sample_predictions = loaded_model.predict(

    test_features.iloc[:5]

)

prediction_table = pd.DataFrame({

    "Actual Price": test_target.iloc[:5].values,

    "Predicted Price": np.round(
        sample_predictions,
        0
    )

})

print("\n")
print("=" * 60)
print("Sample Predictions")
print("=" * 60)

print(prediction_table)